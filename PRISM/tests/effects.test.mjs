test('every effect handles empty and single LED devices, palette limits, and zero brightness', () => {
  const palettes = [['#000000'], ['#000000','#ffffff','#ff0000','#00ff00','#0000ff','#00ffff','#ff00ff','#ffff00']];
  for (const effect of EFFECTS) for (const colors of palettes) for (const edge of [1, 100]) {
    const settings = config(effect, { colors, speed: edge, scale: edge, direction: 'reverse' });
    assert.deepEqual(renderFrame(0, settings, 499), []);
    for (const count of [1, 97]) for (const time of [0, 0.51, 499]) {
      const frame = renderFrame(count, settings, time);
      assert.equal(frame.length, count);
      assert.ok(frame.every(color => Number.isInteger(color) && color >= 0 && color <= 0xffffff), effect);
      assert.ok(renderFrame(count, { ...settings, brightness: 0 }, time).every(color => color === 0), effect);
    }
  }
});

test('browser preview samples match the hardware RGB frame including brightness rounding', () => {
  for (const effect of EFFECTS) for (const direction of ['forward', 'reverse']) {
    const settings = config(effect, { direction, brightness: 37, colors: ['#812bd1', '#c40aff', '#40e9bc'], speed: 17, scale: 83 });
    const frame = renderFrame(23, settings, 1.37), sample = createEffectSampler(settings, 1.37);
    for (let index = 0; index < frame.length; index++) {
      const { color, alpha } = sample(index / (frame.length - 1), index);
      assert.ok(alpha >= 0 && alpha <= 1);
      assert.deepEqual(channels(frame[index]), color.map(value => Math.round(value * alpha)), `${effect}/${direction}/${index}`);
    }
  }
  assert.equal(createEffectSampler({}, 0)(0).alpha, 0.8, 'preview retains default brightness');
});

test('colorcycle blends the chosen palette uniformly and closes the color loop', () => {
  const settings = config('colorcycle', { colors: ['#ff0000', '#00ff00'] });
  const initial = atPhase(31, settings, 0), middle = atPhase(31, settings, 0.25), second = atPhase(31, settings, 0.5);
  assert.ok(initial.every(color => color === 0x0000ff));
  assert.ok(middle.every(color => color === 0x008080));
  assert.ok(second.every(color => color === 0x00ff00));
  assert.deepEqual(atPhase(31, settings, 1), initial);
  assert.deepEqual(atPhase(31, { ...settings, scale: 100 }, 0.25), middle);
});

test('comet moves its bright head, leaves a tail behind, and changes tail length', () => {
  const settings = config('comet', { colors: ['#ffffff'] });
  const first = atPhase(101, settings, 0.3), later = atPhase(101, settings, 0.6);
  assert.equal(peak(first), 30);
  assert.equal(peak(later), 60);
  assert.ok(light(first[20]) > light(first[40]), 'tail follows rather than precedes the head');
  assert.deepEqual(atPhase(101, { ...settings, direction: 'reverse' }, 0.3), first.toReversed());
  const narrow = atPhase(101, { ...settings, scale: 1 }, 0.5), wide = atPhase(101, { ...settings, scale: 100 }, 0.5);
  assert.ok(wide.filter(color => light(color) > 100).length > narrow.filter(color => light(color) > 100).length);
});

test('chase carries separated lights along the strip and scale controls repetition', () => {
  const settings = config('chase', { colors: ['#ffffff'], scale: 100 * 0.5 / 5.5 });
  const first = atPhase(101, settings, 0.1), later = atPhase(101, settings, 0.3);
  assert.equal(peak(first), 24);
  assert.equal(peak(later), 44);
  assert.ok(light(first[24]) > light(first[64]) * 10);
  assert.deepEqual(atPhase(101, { ...settings, direction: 'reverse' }, 0.1), first.toReversed());
  assert.notDeepEqual(atPhase(101, { ...settings, scale: 100 }, 0.1), first);
});

test('scanner reaches both endpoints, turns around, and honors beam width and start direction', () => {
  const settings = config('scanner', { colors: ['#ffffff'] });
  assert.deepEqual([0, 0.5, 1, 1.5, 2].map(phase => peak(atPhase(101, settings, phase))), [0, 50, 100, 50, 0]);
  assert.equal(peak(atPhase(101, { ...settings, direction: 'reverse' }, 0.25)), 75);
  const narrow = atPhase(101, { ...settings, scale: 1 }, 0.5), wide = atPhase(101, { ...settings, scale: 100 }, 0.5);
  assert.ok(wide.filter(color => light(color) > 100).length > narrow.filter(color => light(color) > 100).length);
});

test('ripple remains symmetric about the center while waves move in either direction', () => {
  const settings = config('ripple');
  const frame = atPhase(101, settings, 0.23);
  assert.deepEqual(frame, frame.toReversed());
  assert.notDeepEqual(atPhase(101, settings, 0.44), frame);
  assert.notDeepEqual(atPhase(101, { ...settings, direction: 'reverse' }, 0.23), frame);
  assert.notDeepEqual(atPhase(101, { ...settings, scale: 1 }, 0.23), frame);
});

test('stripes use only selected colors, move, reverse, and become denser with scale', () => {
  const settings = config('stripes'), colors = new Set([0x0000ff, 0x00ff00, 0xff0000]);
  const frame = atPhase(151, settings, 0.37);
  assert.ok(frame.every(color => colors.has(color)));
  assert.deepEqual(new Set(frame), colors);
  assert.notDeepEqual(atPhase(151, settings, 0.5), frame);
  assert.deepEqual(atPhase(151, { ...settings, direction: 'reverse' }, 0.37), frame.toReversed());
  assert.ok(transitions(atPhase(151, { ...settings, scale: 100 }, 0.37)) > transitions(atPhase(151, { ...settings, scale: 1 }, 0.37)));
});

test('fire is deterministic, changes smoothly, and honors a custom non-fire palette', () => {
  const settings = config('fire', { colors: ['#000030', '#0000ff'] });
  const frame = renderFrame(97, settings, 2.345), next = renderFrame(97, settings, 2.3451);
  assert.deepEqual(renderFrame(97, settings, 2.345), frame);
  assert.ok(frame.every(color => (color & 0xffff) === 0), 'a blue palette never produces hardcoded orange or red');
  assert.ok(frame.some(color => color !== frame[0]), 'flame structure varies along the strip');
  assert.ok(next.every((color, index) => Math.abs(channels(color)[2] - channels(frame[index])[2]) <= 1), 'small time steps have no random flashes');
  assert.notDeepEqual(renderFrame(97, settings, 3.345), frame);
  assert.notDeepEqual(renderFrame(97, { ...settings, scale: 1 }, 2.345), frame);
  assert.deepEqual(renderFrame(97, { ...settings, direction: 'reverse' }, 2.345), frame.toReversed());
});

test('aurora layers the chosen colors into animated bands and responds to scale and direction', () => {
  const settings = config('aurora', { colors: ['#000030', '#0000ff'] });
  const frame = renderFrame(97, settings, 1.71);
  assert.ok(frame.every(color => (color & 0xffff) === 0));
  assert.ok(frame.some(color => color !== frame[0]));
  assert.notDeepEqual(renderFrame(97, settings, 2.3), frame);
  assert.notDeepEqual(renderFrame(97, { ...settings, scale: 1 }, 1.71), frame);
  assert.deepEqual(renderFrame(97, { ...settings, direction: 'reverse' }, 1.71), frame.toReversed());
});

